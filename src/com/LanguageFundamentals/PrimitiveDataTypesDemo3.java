package com.LanguageFundamentals;

public class PrimitiveDataTypesDemo3 {
	// Primitive Data Types -- 8
	byte age = 38;
	short id = 1201;
	int marks = 100;
	long mob = 97628761L;
	float height = 7.1f;
	double weight = 75.8d;
	char grade = 'A';
	boolean result = true;

//	Non primitive data types
	String name = "Shubham";

	public static void main(String[] args) {
		PrimitiveDataTypesDemo3 d1 = new PrimitiveDataTypesDemo3();
		System.out.println("Main Method Started");
		System.out.println(d1.age);
		System.out.println(d1.id);
		System.out.println(d1.marks);
		System.out.println(d1.mob);
		System.out.println(d1.height);
		System.out.println(d1.weight);
		System.out.println(d1.grade);
		System.out.println(d1.result);
		System.out.println(d1.name);
		System.out.println("Main Method Ended");

	}

}
