package com.javaintro;

public class Statements {
	public static void main(String [] args) {
		System.out.println("Good Morninng");     // prints a String
		System.out.println('A');                // Prints a Character
		System.out.println(25.0F);              //prints a Floating Value
		System.out.println(true);               //prints a boolean value
		System.out.println(9640569745L);       //prints a Long value
		System.out.println(20);                //prints a integer
		System.out.println(50.6);           // prints decimal value
		}

	}
